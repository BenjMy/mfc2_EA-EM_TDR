#!/usr/bin/env python3
"""
hyp5_layer_depths.py -- HYPOTHESIS 5 on the REAL data (or the synthetic mirror, ``--data synthetic``).

QUESTION: do the layer interfaces have to be inverted, or can they be fixed? Same base scenario, same
solver, same WS freedom; only ``fixed_depths`` changes:

    fixed   interfaces stay at the scenario's ``depths0`` (what 17 of 19 real scenarios do)
    free    EMagPy also inverts the interface depths, starting from ``depths0``

Fixed depths take the depth question out of the calibration (and are faster with L-BFGS-B: x4 CS,
x1.4 FSlin; free depths are 2-7 x SLOWER, see em_options.py). Free depths can absorb a wrong layer
model, but their members spread (a factor ~2 in EC in the synthetic diagnosis) and the best-misfit
member can be worse than the ensemble mean. This script puts the RMSE at the TDR probes of both modes
side by side.

``--em-method`` accepts lbfgsb (default), rope and base; ``lbfgsbfix`` is NOT offered because it forces
``fixed_depths = true`` and would cancel the factor under test.

Per mode: one calibrated scenario and one K = 0 reference (all four WS parameters pinned; shares the
mode's Step 1 cache). Step 1 depends on the depth mode, so each mode has its OWN cache / run folder.

Usage
-----
    python hyp5_layer_depths.py --dry-run
    python hyp5_layer_depths.py --fast                    # smoke test, never a result
    python hyp5_layer_depths.py                           # fixed and free
    python hyp5_layer_depths.py --depth-modes free --no-k0
    python hyp5_layer_depths.py --base real_L3_base       # same test, 3 layers
    python hyp5_layer_depths.py --data synthetic --base mfc2_real_synthetic_mirror
"""
from __future__ import annotations

import argparse
import os
import sys

import hyp_common as hc

QUESTION = "Does inverting the layer interface depths (free) beat fixing them at depths0?"
TAG = "hyp5"
OUT_DIR = os.path.join(hc.OUT_ROOT, "hyp5_layer_depths")
DEPTH_MODES = {"fixed": "interfaces fixed at depths0", "free": "interfaces inverted, start at depths0"}
EM_CHOICES = ("lbfgsb", "rope", "base")     # no lbfgsbfix: it would override fixed_depths
PARENT = "real_depth_parent"
SUMMARY_COLUMNS = ["scenario", "depth_mode", "k0"]


def scenario_name(mode: str) -> str:
    return f"real_depth_{mode}"


def k0_name(mode: str) -> str:
    # not '<name>_k0': run_log rows are matched by name prefix, so one name must not start another
    return f"real_depth_k0_{mode}"


K0_NAMES = tuple(k0_name(m) for m in DEPTH_MODES)


def build_config(base_raw: dict, modes: list[str], out_dir: str, base: str,
                 fast: bool = False, with_k0: bool = True) -> dict:
    """One parent (copy of the base) + one child per depth mode (+ its K = 0 reference)."""
    unknown = [m for m in modes if m not in DEPTH_MODES]
    if unknown:
        raise ValueError(f"unknown depth mode(s) {unknown}; choose from {list(DEPTH_MODES)}")
    parent = hc.make_parent(
        base_raw, cache_tag=f"hyp5_{base}", out_dir=out_dir, fast=fast,
        description="Parent of the layer-depth hypothesis (see hyp5_layer_depths.py).")
    cfg = {"_comment": ["GENERATED by hyp5_layer_depths.py -- do not edit, re-run the script.",
                        "Children differ ONLY by fixed_depths (and their own cache / run folder)."],
           PARENT: parent}
    for m in modes:
        tag = f"hyp5_{base}_{m}"
        cfg[scenario_name(m)] = {
            "extends": PARENT,
            "description": f"Layer depths {m} ({DEPTH_MODES[m]}); otherwise = {base}.",
            "fixed_depths": m == "fixed",
            "output_dir": os.path.join(out_dir, m, "runs"), "cache_tag": tag}
        if with_k0:
            cfg[k0_name(m)] = hc.k0_child(scenario_name(m), base=base, out_dir=os.path.join(out_dir, m),
                                          cache_tag=tag, what=f"the layer-depth hypothesis ({m})")
    return cfg


def main(argv: list[str] | None = None) -> int:
    argv, extra = hc.split_extra(list(sys.argv[1:] if argv is None else argv))
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0],
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    g = ap.add_argument_group("this study: fixed or free layer depths")
    g.add_argument("--depth-modes", nargs="+", default=list(DEPTH_MODES), choices=list(DEPTH_MODES),
                   metavar="MODE", help="depth modes to run (default: both). "
                   + "; ".join(f"{k} = {v}" for k, v in DEPTH_MODES.items()))
    hc.add_k0_arg(ap)
    hc.add_common_args(ap, default_out_dir=OUT_DIR, em_choices=EM_CHOICES)
    args = hc.parse_args(ap, argv)

    try:
        base_raw = hc.resolve_base(args.config, args.base)
    except KeyError as exc:
        ap.error(str(exc))
    modes = list(dict.fromkeys(args.depth_modes))
    cfg = build_config(base_raw, modes, args.out_dir, args.base, args.fast, not args.no_k0)
    names, info, plan = [], {}, []
    for m in modes:
        names.append(scenario_name(m))
        info[scenario_name(m)] = {"depth_mode": m, "k0": "no"}
        plan.append(f"  {m:6s} {DEPTH_MODES[m]}; own Step 1 cache hyp5_{args.base}_{m}")
        if not args.no_k0:
            names.append(k0_name(m))
            info[k0_name(m)] = {"depth_mode": m, "k0": "yes"}
    if "free" in modes and getattr(args, "em_method", "lbfgsb") != "rope":
        plan.append("NOTE: L-BFGS-B with FREE depths is 2-7 x slower than with fixed depths (em_options.py)")
    if not args.no_k0:
        plan.append("K = 0 reference per mode: all WS parameters pinned, shares that mode's Step 1 cache")
    return hc.execute(tag=TAG, cfg=cfg, names=names, args=args, extra=extra, plan_lines=plan,
                      row_info=info, extra_columns=SUMMARY_COLUMNS)


if __name__ == "__main__":
    sys.exit(main())
