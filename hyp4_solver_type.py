#!/usr/bin/env python3
"""
hyp4_solver_type.py -- HYPOTHESIS 4 on the REAL data (or the synthetic mirror, ``--data synthetic``).

QUESTION: does the EM inversion solver alone change the calibration? ROPE (random sampler, EMagPy
default ``rep = 100``) against L-BFGS-B (deterministic), with EVERYTHING else identical: same base
scenario, same layers and depth mode, same forward models, same alphas, same WS freedom.

``diagnose_ec_inversion.py`` found ROPE does not fit the synthetic data (ECa misfit ~600 %, K = 0 floor
0.13-0.15 m3/m3) while L-BFGS-B does (misfit ~5 %, floor ~0.02). This script asks the same question
through the whole pipeline and on the real data, so the RMSE at the TDR probes of the two solvers can
be read side by side.

The solver is the factor under test, so there is NO ``--em-method`` option here (use ``--solvers``).
The depth mode is the base scenario's own (real scenarios: fixed depths; for the fixed / free
question use ``hyp5_layer_depths.py``).

Per solver: one calibrated scenario (the base scenario's WS freedom) and one K = 0 reference (all four
WS parameters pinned, nothing calibrated; it shares the solver's Step 1 cache, so it only costs
Steps 2-6). Step 1 depends on the solver, so each solver has its OWN cache / run folder.

Usage
-----
    python hyp4_solver_type.py --dry-run
    python hyp4_solver_type.py --fast                     # smoke test, never a result
    python hyp4_solver_type.py                            # both solvers, calibrate stage
    python hyp4_solver_type.py --solvers lbfgsb --no-k0
    python hyp4_solver_type.py --data synthetic --base mfc2_real_synthetic_mirror
    python hyp4_solver_type.py --stage both -- --em-njobs 4    # flags after '--' go to run_one_scenario.sh

Cost: L-BFGS-B with FIXED depths is faster than ROPE (x4 with CS, x1.4 with FSlin, 4 layers); with FREE
depths it is 2-7 x slower (see em_options.py).
"""
from __future__ import annotations

import argparse
import os
import sys

import em_options
import hyp_common as hc

QUESTION = "Does the EM inversion solver (ROPE or L-BFGS-B) change the calibration, everything else equal?"
TAG = "hyp4"
OUT_DIR = os.path.join(hc.OUT_ROOT, "hyp4_solver_type")
SOLVERS = {"rope": "ROPE (random sampler, rep = 100)", "lbfgsb": "L-BFGS-B (deterministic)"}
EM_CHOICES: tuple[str, ...] = ()           # no --em-method: the solver is the factor (see run_all_hypotheses)
PARENT = "real_solver_parent"
SUMMARY_COLUMNS = ["scenario", "solver", "k0"]


def scenario_name(solver: str) -> str:
    return f"real_solver_{solver}"


def k0_name(solver: str) -> str:
    # not '<name>_k0': run_log rows are matched by name prefix, so one name must not start another
    return f"real_solver_k0_{solver}"


K0_NAMES = tuple(k0_name(s) for s in SOLVERS)


def build_config(base_raw: dict, solvers: list[str], out_dir: str, base: str,
                 fast: bool = False, with_k0: bool = True) -> dict:
    """One parent (copy of the base) + one child per solver (+ its K = 0 reference)."""
    unknown = [s for s in solvers if s not in SOLVERS]
    if unknown:
        raise ValueError(f"unknown solver(s) {unknown}; choose from {list(SOLVERS)}")
    parent = hc.make_parent(
        base_raw, cache_tag=f"hyp4_{base}", out_dir=out_dir, fast=fast,
        description="Parent of the solver-type hypothesis (see hyp4_solver_type.py).")
    cfg = {"_comment": ["GENERATED by hyp4_solver_type.py -- do not edit, re-run the script.",
                        "Children differ ONLY by param_grid.method (and their own cache / run folder)."],
           PARENT: parent}
    for s in solvers:
        folder = os.path.join(out_dir, s, "runs")
        tag = f"hyp4_{base}_{s}"
        cfg[scenario_name(s)] = {
            "extends": PARENT,
            "description": f"Solver {SOLVERS[s]}; otherwise = {base}.",
            "param_grid": {"method": [em_options.method_name(s)]},
            "output_dir": folder, "cache_tag": tag}
        if with_k0:
            cfg[k0_name(s)] = hc.k0_child(scenario_name(s), base=base, out_dir=os.path.join(out_dir, s),
                                          cache_tag=tag, what=f"the solver hypothesis ({s})")
    return cfg


def main(argv: list[str] | None = None) -> int:
    argv, extra = hc.split_extra(list(sys.argv[1:] if argv is None else argv))
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0],
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    g = ap.add_argument_group("this study: solver type")
    g.add_argument("--solvers", nargs="+", default=list(SOLVERS), choices=list(SOLVERS), metavar="SOLVER",
                   help="EM solvers to compare (default: both). " + "; ".join(f"{k} = {v}" for k, v in SOLVERS.items()))
    hc.add_k0_arg(ap)
    hc.add_common_args(ap, default_out_dir=OUT_DIR, em_choices=EM_CHOICES)
    args = hc.parse_args(ap, argv)

    try:
        base_raw = hc.resolve_base(args.config, args.base)
    except KeyError as exc:
        ap.error(str(exc))
    solvers = list(dict.fromkeys(args.solvers))
    cfg = build_config(base_raw, solvers, args.out_dir, args.base, args.fast, not args.no_k0)
    names, info, plan = [], {}, []
    for s in solvers:
        names.append(scenario_name(s))
        info[scenario_name(s)] = {"solver": s, "k0": "no"}
        plan.append(f"  {s:7s} {SOLVERS[s]}; own Step 1 cache hyp4_{args.base}_{s}")
        if not args.no_k0:
            names.append(k0_name(s))
            info[k0_name(s)] = {"solver": s, "k0": "yes"}
    if not args.no_k0:
        plan.append("K = 0 reference per solver: all WS parameters pinned, shares that solver's Step 1 cache")
    plan.append("depth mode and layers: the base scenario's own (hyp5_layer_depths.py tests fixed vs free)")
    return hc.execute(tag=TAG, cfg=cfg, names=names, args=args, extra=extra, plan_lines=plan,
                      row_info=info, extra_columns=SUMMARY_COLUMNS)


if __name__ == "__main__":
    sys.exit(main())
