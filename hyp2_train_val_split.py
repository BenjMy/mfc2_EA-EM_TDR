#!/usr/bin/env python3
"""
hyp2_train_val_split.py -- HYPOTHESIS 2 on the REAL data.

QUESTION: is the calibration still good on data it has NOT seen? The default pipeline
fits Waxman-Smits and selects the ensemble size K on ALL TDR observations, so the
reported RMSE is in-sample. This runs the same scenario with each train/validation
split and reports the held-out (out-of-sample) RMSE.

Variants (one generated scenario each; ``train_val_split`` field, Loiseau et al. 2026)
    off               legacy: fit and select K on everything (in-sample reference)
    alternate_sorted  paper's fallback -- NOT fully independent (a probe or time step
                      can sit in both subsets)
    by_probe          hold out whole probes -- fully independent in space
    by_time_block     hold out whole time blocks -- fully independent in time
    random            for comparison only

Step 1 (the expensive ensemble inversion) does not depend on the split, so all
variants share ONE ``output_dir`` / ``cache_tag`` (fingerprint-checked).

Usage
-----
    python hyp2_train_val_split.py --dry-run                 # show the plan
    python hyp2_train_val_split.py --fast                    # smoke test
    python hyp2_train_val_split.py --methods by_probe off    # a subset
    python hyp2_train_val_split.py --base real_L3_base       # same test, 3 layers
"""
from __future__ import annotations

import argparse
import os
import sys

import hyp_common as hc

QUESTION = "Is the calibration still good on held-out data (train/validation split)?"
TAG = "hyp2"
OUT_DIR = os.path.join(hc.OUT_ROOT, "hyp2_train_val_split")

METHODS = {
    "off": "legacy, in-sample reference",
    "alternate_sorted": "NOT fully independent",
    "by_probe": "fully independent (space)",
    "by_time_block": "fully independent (time)",
    "random": "comparison only",
}
SUMMARY_COLUMNS = ["scenario", "split"]


def scenario_name(method: str) -> str:
    return f"real_tv_{method}"


K0_NAME = "real_tv_k0"


def build_config(base_raw: dict, methods: list[str], out_dir: str, base: str,
                 fast: bool = False, with_k0: bool = True) -> dict:
    parent = hc.make_parent(
        base_raw, cache_tag=f"hyp2_{base}", out_dir=out_dir, fast=fast,
        description="Parent of the train/validation hypothesis (see hyp2_train_val_split.py).")
    cfg = {"_comment": ["GENERATED by hyp2_train_val_split.py -- do not edit, re-run the script."],
           "real_tv_parent": parent}
    for m in methods:
        cfg[scenario_name(m)] = {
            "extends": "real_tv_parent",
            "description": f"Train/validation split '{m}' ({METHODS[m]}); otherwise = {base}.",
            "train_val_split": m,
            "output_dir": os.path.join(out_dir, "runs"),   # one shared Step 1 cache
            "cache_tag": f"hyp2_{base}",
        }
    if with_k0:
        cfg[K0_NAME] = hc.k0_child("real_tv_parent", base=base, out_dir=out_dir, cache_tag=f"hyp2_{base}",
                                   what="the train/validation hypothesis")
    return cfg


def main(argv: list[str] | None = None) -> int:
    argv, extra = hc.split_extra(list(sys.argv[1:] if argv is None else argv))
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0],
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--methods", nargs="+", default=list(METHODS), choices=list(METHODS),
                    help=f"split methods to run (default: all of {list(METHODS)})")
    hc.add_k0_arg(ap)
    hc.add_common_args(ap, default_out_dir=OUT_DIR)
    args = hc.parse_args(ap, argv)

    try:
        base_raw = hc.resolve_base(args.config, args.base)
    except KeyError as exc:
        ap.error(str(exc))
    cfg = build_config(base_raw, args.methods, args.out_dir, args.base, args.fast, not args.no_k0)
    names = [scenario_name(m) for m in args.methods]
    plan = [f"  {m:17s} {METHODS[m]}" for m in args.methods]
    info = {scenario_name(m): {"split": m} for m in args.methods}
    if not args.no_k0:
        names.append(K0_NAME)
        plan.append(f"  {'K = 0':17s} reference: all WS parameters pinned (nothing calibrated)")
        info[K0_NAME] = {"split": "K0"}
    return hc.execute(tag=TAG, cfg=cfg, names=names, args=args, extra=extra,
                      plan_lines=plan, row_info=info, extra_columns=SUMMARY_COLUMNS)


if __name__ == "__main__":
    sys.exit(main())
