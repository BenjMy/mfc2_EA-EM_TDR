#!/usr/bin/env python3
"""
hyp3_localized_bandwidth.py -- HYPOTHESIS 3 on the REAL data.

QUESTION: does letting the Waxman-Smits parameters vary in space (a kernel-localized
Step 2 fit) beat one global set per horizon, and at which bandwidth?

The localized fit weights every TDR observation of a horizon by a Gaspari-Cohn kernel
of its distance to the target point: bandwidth -> infinity = the global per-horizon
fit, bandwidth -> 0 = the nearest probe. The bandwidth (m) is chosen from the list
given here by leave-one-probe-out cross-validation (``ws_localized_bandwidth_sweep``).
It only reads probe-matched points, so it runs in the calibration stage.

Every real scenario already carries a default sweep; this script runs ONE scenario with
YOUR candidate list so you can test other values without editing the JSON.

Usage
-----
    python hyp3_localized_bandwidth.py --dry-run
    python hyp3_localized_bandwidth.py                          # default candidates
    python hyp3_localized_bandwidth.py --bandwidths 1 2 5 10 15 20
    python hyp3_localized_bandwidth.py --base real_L3_base      # same test, 3 layers
    python hyp3_localized_bandwidth.py --footprint              # + McNeill footprint diagnostic
"""
from __future__ import annotations

import argparse
import os
import sys

import hyp_common as hc

QUESTION = "Does a spatially localized WS calibration help, and at what bandwidth?"
TAG = "hyp3"
OUT_DIR = os.path.join(hc.OUT_ROOT, "hyp3_localized_bandwidth")
DEFAULT_BANDWIDTHS = [1, 2, 5, 10, 15, 20]
NAME = "real_bw_sweep"
K0_NAME = "real_bw_k0"


def build_config(base_raw: dict, bandwidths: list[float], out_dir: str, base: str,
                 fast: bool = False, with_k0: bool = True) -> dict:
    parent = hc.make_parent(
        base_raw, cache_tag=f"hyp3_{base}", out_dir=out_dir, fast=fast,
        description="Parent of the localized-bandwidth hypothesis (see hyp3_localized_bandwidth.py).")
    cfg = {"_comment": ["GENERATED by hyp3_localized_bandwidth.py -- do not edit, re-run the script."],
           "real_bw_parent": parent,
           NAME: {"extends": "real_bw_parent",
                  "description": f"Localized-bandwidth sweep {list(bandwidths)}; otherwise = {base}.",
                  "ws_localized_bandwidth_sweep": list(bandwidths),
                  "output_dir": os.path.join(out_dir, "runs"),
                  "cache_tag": f"hyp3_{base}"}}
    if with_k0:
        cfg[K0_NAME] = hc.k0_child("real_bw_parent", base=base, out_dir=out_dir, cache_tag=f"hyp3_{base}",
                                   what="the localized-bandwidth hypothesis")
    return cfg


def main(argv: list[str] | None = None) -> int:
    argv, extra = hc.split_extra(list(sys.argv[1:] if argv is None else argv))
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0],
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--bandwidths", nargs="+", type=float, default=DEFAULT_BANDWIDTHS,
                    help=f"candidate bandwidths in m (default {DEFAULT_BANDWIDTHS})")
    ap.add_argument("--footprint", action="store_true",
                    help="also pass --em-footprint-diagnostic (Step 5c McNeill depth weighting)")
    hc.add_k0_arg(ap)
    hc.add_common_args(ap, default_out_dir=OUT_DIR)
    args = hc.parse_args(ap, argv)
    if any(b <= 0 for b in args.bandwidths):
        ap.error("bandwidths must be positive")
    if args.footprint:
        extra = ["--em-footprint-diagnostic", *extra]

    try:
        base_raw = hc.resolve_base(args.config, args.base)
    except KeyError as exc:
        ap.error(str(exc))
    cfg = build_config(base_raw, args.bandwidths, args.out_dir, args.base, args.fast, not args.no_k0)
    plan = [f"candidate bandwidths [m]: {args.bandwidths}  (chosen by leave-one-probe-out CV)"]
    names = [NAME]
    if not args.no_k0:
        names.append(K0_NAME)
        plan.append("K = 0 reference: all WS parameters pinned (nothing calibrated), shares the Step 1 cache")
    return hc.execute(tag=TAG, cfg=cfg, names=names, args=args, extra=extra, plan_lines=plan)


if __name__ == "__main__":
    sys.exit(main())
